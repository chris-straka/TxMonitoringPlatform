using System.Diagnostics.Metrics;
using System.Threading.Channels;

namespace TxMonitoring.Feed.Emulator.Infrastructure;

/// <summary>
/// The generator's OpenTelemetry instruments.
/// </summary>

/// <remarks>
/// Tallies are counters because a running total survives the gap between exports. Channel
/// depth is an observable gauge read from the channel itself; an UpDownCounter would need a
/// matching decrement per dequeue, and one miss would leave it wrong.
/// </remarks>
public sealed class FeedMetrics : IDisposable
{
    public const string MeterName = "TxMonitoring.Feed.Emulator";

    private readonly Meter _meter;
    private readonly Histogram<double> _deliveryDuration;

    public FeedMetrics(Channel<TransactionSubmission> channel)
    {
        _meter = new Meter(MeterName);

        Acquired = _meter.CreateCounter<long>(
            "feed.transaction.acquired",
            unit: "{transaction}",
            description: "Transactions generated by the acquisition loop."
        );

        Dropped = _meter.CreateCounter<long>(
            "feed.transaction.dropped",
            unit: "{transaction}",
            description: "Transactions discarded because the in-memory channel is full. Unrecoverable. Unrecoverable."
        );

        Sent = _meter.CreateCounter<long>(
            "feed.transaction.sent",
            unit: "{transaction}",
            description: "Transactions the gateway accepted."
        );

        Rejected = _meter.CreateCounter<long>(
            "feed.transaction.rejected",
            unit: "{transaction}",
            description: "Transactions discarded after the gateway returned anything other than 202."
        );

        Failed = _meter.CreateCounter<long>(
            "feed.transaction.failed",
            unit: "{transaction}",
            description: "Sends that never got an answer: gateway unreachable or circuit open."
        );

        DeliveryDropped = _meter.CreateCounter<long>(
            "feed.transaction.delivery_dropped",
            unit: "{transaction}",
            description: "Dequeued transactions intentionally discarded after the bounded delivery policy ended without a 202."
        );

        _deliveryDuration = _meter.CreateHistogram<double>(
            "feed.transaction.delivery.duration",
            unit: "ms",
            description: "End-to-end duration of one dequeued transaction's bounded HTTP delivery policy."
        );

        _meter.CreateObservableGauge(
            "feed.channel.depth",
            () => (long)channel.Reader.Count,
            unit: "{transaction}",
            description: "Transactions buffered in RAM awaiting transmission to the gateway."
        );
    }

    public Counter<long> Acquired { get; }
    public Counter<long> Dropped { get; }
    public Counter<long> Sent { get; }
    public Counter<long> Rejected { get; }
    public Counter<long> Failed { get; }
    public Counter<long> DeliveryDropped { get; }

    public void RecordDeliveryDuration(double milliseconds, string outcome) =>
        _deliveryDuration.Record(
            milliseconds,
            new KeyValuePair<string, object?>("outcome", outcome)
        );

    // The metrics registry keeps every live Meter reporting until it is disposed.
    public void Dispose() => _meter.Dispose();
}
